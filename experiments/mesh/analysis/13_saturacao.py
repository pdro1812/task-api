#!/usr/bin/env python3
"""Tabela de vazão máxima (tab:sat) a partir de todas as buscas de saturação.

Buscas: a bissecção refinada (SATF_ em saturacao-fina/, 4 passos depois da bateria) e as subidas sem censura
(SATR_ em saturacao-rep/rep<N>/ e ci4/saturacao/, SUBIR=1 de 04-saturacao.sh: sobe 5% até duas reprovações
seguidas). Uma bissecção em que os 4 passos passaram é censurada: o valor é só um limite inferior, entra no
intervalo min-max mas não na mediana. Valor da célula = mediana das buscas não censuradas.

Uso: 13_saturacao.py <resultados> [--saida-csv sat.csv] [--saida-tex ../paper/tables/saturacao.tex]
"""
import argparse
import csv
import glob
import os
import re
import statistics

SLO = {"echo": 20, "ob": 500, "hotel": 100}
ORDEM = ["B", "IA4", "CI4", "IA7", "LK", "IS", "CI"]
NOME = {"echo": "Echo", "ob": "OB", "hotel": "HR"}


def le_env(path, prefixo):
    out = {}
    for linha in open(path):
        m = re.match(rf"^{prefixo}_(echo|ob|hotel)_([A-Z0-9]+)=(\d+)$", linha.strip())
        if m:
            out[(m.group(2), m.group(1))] = int(m.group(3))
    return out


def censuradas(dir_fina):
    """Células da bissecção em que os 4 passos cumpriram o SLO."""
    passos = {}
    for f in glob.glob(os.path.join(dir_fina, "saturacao-fina-*.tsv")):
        for r in csv.DictReader(open(f), delimiter="\t"):
            ok = float(r["p99_ms"]) <= SLO[r["app"]] and float(r["err"]) <= 0.01 and float(r["dropped"]) <= 0.01
            passos.setdefault((r["config"], r["app"]), []).append(ok)
    return {k for k, v in passos.items() if len(v) == 4 and all(v)}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("resultados")
    ap.add_argument("--saida-csv", default=None)
    ap.add_argument("--saida-tex", default=os.path.join(os.path.dirname(__file__), "..", "paper", "tables", "saturacao.tex"))
    a = ap.parse_args()
    res = a.resultados
    buscas = {}   # (cfg, app) -> [(valor, censurada)]
    fina = os.path.join(res, "saturacao-fina")
    cens = censuradas(fina)
    for k, v in le_env(os.path.join(fina, "saturacao.env"), "SATF").items():
        buscas.setdefault(k, []).append((v, k in cens))
    for f in sorted(glob.glob(os.path.join(res, "saturacao-rep", "rep*", "saturacao-sobe.env"))
                    + sorted(glob.glob(os.path.join(res, "ci4", "saturacao", "*.env")))):
        for k, v in le_env(f, "SATR").items():
            buscas.setdefault(k, []).append((v, False))
    linhas = []
    for (cfg, app), bs in buscas.items():
        boas = [v for v, c in bs if not c]
        todas = [v for v, _ in bs]
        linhas.append({"config": cfg, "app": app, "sat": statistics.median(boas) if boas else min(todas),
                       "min": min(todas), "max": max(todas), "n": len(bs), "n_censurada": sum(c for _, c in bs),
                       "limite_inferior": int(not boas)})
    b = {r["app"]: r["sat"] for r in linhas if r["config"] == "B"}
    for r in linhas:
        r["frac_B"] = r["sat"] / b[r["app"]]
    saida_csv = a.saida_csv or os.path.join(os.path.dirname(__file__), "out", "saturacao.csv")
    os.makedirs(os.path.dirname(saida_csv), exist_ok=True)
    linhas.sort(key=lambda r: (ORDEM.index(r["config"]) if r["config"] in ORDEM else 99, r["app"]))
    with open(saida_csv, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(linhas[0]))
        w.writeheader()
        w.writerows(linhas)
    idx = {(r["config"], r["app"]): r for r in linhas}
    with open(a.saida_tex, "w") as f:
        f.write("% generated by analysis/13_saturacao.py\n\\begin{tabular}{@{}lrrr@{}}\n\\toprule\n")
        f.write("     & Echo & OB & HR \\\\\n\\midrule\n")
        for cfg in ORDEM:
            cel = []
            for app in ("echo", "ob", "hotel"):
                r = idx.get((cfg, app))
                if r is None:
                    cel.append("--")
                    continue
                s = f"{r['sat']:.0f}"
                if r["max"] > r["min"]:
                    s += f"\\,\\tiny[{r['min']}--{r['max']}]"
                if cfg != "B":
                    s += f" ({100 * r['frac_B']:.0f}\\%)"
                if r["limite_inferior"]:
                    s += "$^{\\ddagger}$"
                cel.append(s)
            f.write(f"{cfg} & " + " & ".join(cel) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    for r in linhas:
        print(r["config"], r["app"], r["sat"], f"[{r['min']}-{r['max']}]", "n", r["n"], f"{100 * r['frac_B']:.0f}%",
              "LI" if r["limite_inferior"] else "")
    print(saida_csv, a.saida_tex)


if __name__ == "__main__":
    main()
