#!/usr/bin/env python3
"""Variação entre deploys (revisões de 27/11): OB a 60% e 90%, com a bateria principal (d1; CI4 do run de 21/11)
e dois deploys independentes extras (d2, d3; 15-extras.sh), 3 repetições cada.

Por configuração e carga: mediana do p99 de cada deploy; ICC(1) do log(p99) (fração da variância total que está
entre deploys, ANOVA de um fator com grupos desbalanceados); IC 95% da mediana por bootstrap hierárquico
(reamostra deploys, depois repetições dentro de cada deploy) contra o IC só dentro do deploy principal; e o
tau de Kendall do ranking das configurações entre cada par de deploys.

Uso: 42_deploys.py <bateria-1/cells.csv> <ci4/cells.csv> <deploys/d2/cells.csv> <deploys/d3/cells.csv> [--saida tex]
"""
import argparse
import itertools
import os

import numpy as np
import pandas as pd
from scipy import stats

RNG = np.random.default_rng(2027)
ORDEM = ["B", "IA4", "CI4", "IA7", "LK", "CI", "IS"]


def icc1(grupos):
    """ICC(1) de ANOVA de um fator (Shrout & Fleiss), com n0 para grupos desbalanceados."""
    k = len(grupos)
    ns = np.array([len(g) for g in grupos])
    N = ns.sum()
    media = np.concatenate(grupos).mean()
    msb = sum(n * (g.mean() - media) ** 2 for n, g in zip(ns, grupos)) / (k - 1)
    msw = sum(((g - g.mean()) ** 2).sum() for g in grupos) / (N - k)
    n0 = (N - (ns ** 2).sum() / N) / (k - 1)
    return max(0.0, (msb - msw) / (msb + (n0 - 1) * msw))


def ic_hier(grupos, n=4000):
    meds = []
    for _ in range(n):
        gs = [grupos[i] for i in RNG.integers(0, len(grupos), len(grupos))]
        amostra = np.concatenate([RNG.choice(g, len(g), replace=True) for g in gs])
        meds.append(np.median(amostra))
    return np.quantile(meds, [0.025, 0.975])


def ic_simples(v, n=4000):
    return np.quantile(np.median(RNG.choice(v, (n, len(v)), replace=True), axis=1), [0.025, 0.975])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("principal"); ap.add_argument("ci4"); ap.add_argument("d2"); ap.add_argument("d3")
    ap.add_argument("--saida", default=os.path.join(os.path.dirname(__file__), "..", "paper", "tables", "deploys.tex"))
    a = ap.parse_args()
    p = pd.read_csv(a.principal); p["deploy"] = "d1"
    c = pd.read_csv(a.ci4); c = c[c.config == "CI4"].copy(); c["deploy"] = "d1"
    d2 = pd.read_csv(a.d2); d2["deploy"] = "d2"
    d3 = pd.read_csv(a.d3); d3["deploy"] = "d3"
    df = pd.concat([p, c, d2, d3])
    df = df[(df.app == "ob") & (df.load.astype(int).isin([60, 90]))]
    df["load"] = df.load.astype(int)
    linhas = []
    for (cfg, load), g in df.groupby(["config", "load"]):
        grupos = [np.log(x.p99_ms.values) for _, x in g.groupby("deploy")]
        brutos = [x.p99_ms.values for _, x in g.groupby("deploy")]
        meds = {dep: x.p99_ms.median() for dep, x in g.groupby("deploy")}
        lo, hi = ic_hier(brutos)
        lo1, hi1 = ic_simples(g[g.deploy == "d1"].p99_ms.values)
        linhas.append({"config": cfg, "load": load, **{f"med_{k}": v for k, v in meds.items()},
                       "icc": icc1(grupos), "ic_hier_lo": lo, "ic_hier_hi": hi, "ic_d1_lo": lo1, "ic_d1_hi": hi1,
                       "spread": max(meds.values()) / min(meds.values()) - 1})
    r = pd.DataFrame(linhas)
    pd.set_option("display.width", 220)
    print(r.round(3).to_string(index=False))
    taus = []
    for load in (60, 90):
        x = r[r.load == load].set_index("config")
        for d_a, d_b in itertools.combinations(["d1", "d2", "d3"], 2):
            t = stats.kendalltau(x[f"med_{d_a}"], x[f"med_{d_b}"]).statistic
            taus.append((load, d_a, d_b, t))
            print("tau", load, d_a, d_b, round(t, 3))
    with open(a.saida, "w") as f:
        f.write("% generated by analysis/42_deploys.py\n\\begin{tabular}{@{}lrrrrr@{}}\n\\toprule\n")
        f.write("Config. & d1 & d2 & d3 & ICC & 95\\% CI (deploys) \\\\\n\\midrule\n")
        for cfg in ORDEM:
            x = r[(r.config == cfg) & (r.load == 90)]
            if x.empty:
                continue
            x = x.iloc[0]
            f.write(f"{cfg} & {x.med_d1:.1f} & {x.med_d2:.1f} & {x.med_d3:.1f} & {x.icc:.2f} & "
                    f"{x.ic_hier_lo:.1f}--{x.ic_hier_hi:.1f} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    print(a.saida)


if __name__ == "__main__":
    main()
